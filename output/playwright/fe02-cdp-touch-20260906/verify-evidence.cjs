// Read-only assertions over saved evidence; does not operate a browser or server.
const fs = require('node:fs');
const assert = require('node:assert/strict');
const read = name => JSON.parse(fs.readFileSync(`${__dirname}/${name}`, 'utf8'));
const b = read('before.json'), a = read('after-reload.json'), e = read('browser-evidence.json');
assert.equal(e.sessionCreate.learning_session_id, b.session_id);
assert.equal(e.sessionCreate.status, 'OPEN');
assert.equal(e.reload.sessionResponse.learning_session_id, b.session_id);
assert.equal(e.reload.sessionResponse.status, 'OPEN');
assert.equal(new URL(e.reload.url).searchParams.get('session'), b.session_id);
const pointer = e.gesture.trace.filter(x => ['pointerdown','pointermove','pointerup'].includes(x.type));
assert.equal(pointer.filter(x=>x.type==='pointerdown').length, 1);
assert.equal(pointer.filter(x=>x.type==='pointerup').length, 1);
assert.equal(pointer.filter(x=>x.type==='pointermove').length, 8);
assert(pointer.every(x=>x.isTrusted && x.pointerType==='touch' && x.pointerId===2 && x.itemId==='ones-group-06'));
assert(!e.gesture.trace.some(x=>x.type.includes('cancel')));
const posts=e.network.filter(x=>x.httpMethod==='POST');
assert.equal(posts.length,1);
const p=JSON.parse(posts[0].postData);
assert.equal(p.action_key,'TRANSFER_ITEM');
assert.equal(p.scene_id,b.snapshot.current_scene_id);
assert.equal(p.base_scene_version,2);
assert.deepEqual(p.payload,{item_id:'ones-group-06',from_group_id:'ones-group',to_group_id:'ten-frame'});
assert.equal(e.network.find(x=>x.method==='Network.responseReceived' && x.requestId===posts[0].requestId).status,200);
assert.equal(e.operationResponse.sequence,3);
assert.equal(e.operationResponse.replayed,false);
assert.equal(e.operationResponse.student_interaction_id,null);
assert.equal(a.events.length,b.events.length+1);
assert.equal(a.events.at(-1).action,'TRANSFER_ITEM');
assert.equal(a.events.at(-1).base,2);
assert.equal(a.events.at(-1).resulting,3);
assert.deepEqual(a.messages,b.messages);
assert.deepEqual(a.interactions,b.interactions);
assert.equal(a.executions,b.executions);
assert.equal(a.executions,1);
for(const s of [e.afterSnapshot,e.reload.snapshot,a.snapshot]) {
  assert.equal(s.latest_event_sequence,3);
  assert.equal(s.current_scene_id,b.snapshot.current_scene_id);
  assert.equal(s.current_scene_version,3);
  assert.equal(s.active_scene_contract.scene_version,3);
}
assert.deepEqual(e.afterSnapshot,e.reload.snapshot);
assert.deepEqual(e.reload.snapshot,a.snapshot);
assert(e.afterDOM.includes('إطار العشرة: 10') && e.afterDOM.includes('مجموعة الآحاد: 5'));
assert(e.reload.dom.includes('إطار العشرة: 10') && e.reload.dom.includes('مجموعة الآحاد: 5'));
const itemIds=s=>s.active_scene_seed.items.map(x=>x.id).sort();
assert.deepEqual(itemIds(a.snapshot),itemIds(b.snapshot));
assert.equal(new Set(itemIds(a.snapshot)).size,15);
const groups=a.snapshot.state_payload.ten_frame_group_transfer.groups;
assert.equal(groups['ten-frame'].item_ids.length,10);
assert.equal(groups['ones-group'].item_ids.length,5);
assert(groups['ten-frame'].item_ids.includes('ones-group-06'));
assert(!groups['ones-group'].item_ids.includes('ones-group-06'));
assert.deepEqual([...groups['ten-frame'].item_ids,...groups['ones-group'].item_ids].sort(),itemIds(b.snapshot));
assert(!e.reload.network.some(x=>x.url.endsWith('/operations')));
assert(e.reload.network.some(x=>x.url.endsWith('/events/stream?after_sequence=3') && x.status===200));
assert([...e.openingNetwork,...e.network,...e.reload.network].every(x=>x.status!==401 && x.status!==409));
assert(Object.values(e.buffers).every(x=>!x.hasMore && !x.truncated));
assert(e.cleanup.observerRemoved && e.cleanup.touchEmulationDisabled);
console.log('PASS: fresh-session -> trusted touch drag -> one accepted operation -> authoritative Snapshot -> same-session reload; unchanged Tutor/interaction counts.');
